"""Track B cross-view variants: held-out query viewpoint (ADR-0004).

A variant for held-out view ``v`` is a filter over a stored Track B split
(``data/splits/track_b/seed_<s>.parquet``): support keeps the rows of the other known
viewpoints, validation and test keep the rows of viewpoint ``v``. Rows are never
re-assigned, so every output row carries the partition it had in the parent split and
the parent's leakage guarantees carry over. Rows with the uncertain viewpoint ``-1`` are
excluded from every partition of every variant. A class stays in variant ``v`` only if it
keeps at least ``min_support`` support rows and ``min_test`` test rows after filtering;
the class is charged to the first rule it fails.
"""

from __future__ import annotations

from pathlib import Path

import pandas as pd
from pydantic import BaseModel

from avr.data.split_track_b import split_table
from avr.data.splits_io import SplitManifestOutputs, write_split_manifest

UNCERTAIN_VIEWPOINT = -1
VIEWS: tuple[int, ...] = (1, 2, 3, 4, 5)
PARTITIONS: tuple[str, ...] = ("support", "validation", "test")


class CrossViewThresholds(BaseModel):
    min_support: int = 5
    min_test: int = 1


class ViewEligibility(BaseModel):
    """What held-out view ``view`` keeps and drops from one parent split."""

    view: int
    thresholds: CrossViewThresholds
    classes_before: int
    classes_after: int
    dropped_too_few_support: list[str]
    dropped_no_test: list[str]
    images_before: dict[str, int]
    images_uncertain: dict[str, int]
    images_after: dict[str, int]
    eligible_class_ids: list[str]


def _filter_rows(split: pd.DataFrame, view: int) -> pd.DataFrame:
    known = split[split["viewpoint"] != UNCERTAIN_VIEWPOINT]
    is_support = known["partition"] == "support"
    is_view = known["viewpoint"] == view
    return known[(is_support & ~is_view) | (~is_support & is_view)]


def _partition_counts(frame: pd.DataFrame) -> dict[str, int]:
    return {p: int((frame["partition"] == p).sum()) for p in PARTITIONS}


def _eligible_classes(
    filtered: pd.DataFrame, t: CrossViewThresholds
) -> tuple[list[str], list[str], list[str]]:
    """(kept, dropped for too few support, dropped for no test), each sorted by class_id."""
    counts = pd.crosstab(filtered["class_id"], filtered["partition"]).reindex(
        columns=list(PARTITIONS), fill_value=0
    )
    enough_support = counts["support"] >= t.min_support
    enough_test = counts["test"] >= t.min_test
    kept = sorted(str(c) for c in counts.index[enough_support & enough_test])
    few_support = sorted(str(c) for c in counts.index[~enough_support])
    no_test = sorted(str(c) for c in counts.index[enough_support & ~enough_test])
    return kept, few_support, no_test


def audit_cross_view(
    split: pd.DataFrame, view: int, thresholds: CrossViewThresholds | None = None
) -> ViewEligibility:
    """Count what held-out view ``view`` keeps and drops; drops nothing."""
    t = thresholds or CrossViewThresholds()
    filtered = _filter_rows(split, view)
    kept, few_support, no_test = _eligible_classes(filtered, t)
    kept_rows = filtered[filtered["class_id"].isin(kept)]
    uncertain = split[split["viewpoint"] == UNCERTAIN_VIEWPOINT]
    return ViewEligibility(
        view=view,
        thresholds=t,
        classes_before=int(split["class_id"].nunique()),
        classes_after=len(kept),
        dropped_too_few_support=few_support,
        dropped_no_test=no_test,
        images_before=_partition_counts(split),
        images_uncertain=_partition_counts(uncertain),
        images_after=_partition_counts(kept_rows),
        eligible_class_ids=kept,
    )


def cross_view_variant(
    split: pd.DataFrame, view: int, thresholds: CrossViewThresholds | None = None
) -> pd.DataFrame:
    """The variant for held-out view ``view``: filtered rows of the eligible classes.

    Columns and partitions are those of ``split``; rows are sorted by ``image_id``.
    """
    t = thresholds or CrossViewThresholds()
    filtered = _filter_rows(split, view)
    kept, _, _ = _eligible_classes(filtered, t)
    out = filtered[filtered["class_id"].isin(kept)]
    return out.sort_values("image_id").reset_index(drop=True)


def _table(rows: list[list[object]]) -> str:
    return "\n".join("| " + " | ".join(str(c) for c in row) + " |" for row in rows)


def write_cross_view_report(audits: dict[int, ViewEligibility], seed: int, path: Path) -> Path:
    """Render the per-view eligibility table for one parent seed as Markdown."""
    first = next(iter(audits.values()))
    t = first.thresholds
    lines = [
        f"# Track B cross-view eligibility, seed {seed}",
        "",
        "Generated by `scripts/build_cross_view_splits.py` (ADR-0004); do not edit by hand.",
        f"Each variant filters `data/splits/track_b/seed_{seed}.parquet`: support keeps the",
        "other known viewpoints, validation and test keep the held-out viewpoint only. No row",
        "changes partition. Rows with the uncertain viewpoint `-1` are excluded from every",
        "partition of every variant. A class is kept only if it retains at least",
        f"{t.min_support} support and {t.min_test} test rows after filtering; a class is charged",
        "to the first rule it fails (support first, then test). This report is written before",
        "any variant table.",
        "",
        "## Parent split",
        "",
        f"Classes: {first.classes_before}. Images per partition: "
        + ", ".join(f"{p} {n}" for p, n in first.images_before.items())
        + "; of which uncertain viewpoint: "
        + ", ".join(f"{p} {n}" for p, n in first.images_uncertain.items())
        + ".",
        "",
        "## Eligibility per held-out view",
        "",
        _table(
            [
                [
                    "held-out view",
                    "classes before",
                    "classes kept",
                    "dropped: too few support",
                    "dropped: no test image",
                    "support images kept",
                    "validation images kept",
                    "test images kept",
                ],
                ["---"] * 8,
                *[
                    [
                        a.view,
                        a.classes_before,
                        a.classes_after,
                        len(a.dropped_too_few_support),
                        len(a.dropped_no_test),
                        a.images_after["support"],
                        a.images_after["validation"],
                        a.images_after["test"],
                    ]
                    for a in audits.values()
                ],
            ]
        ),
        "",
        "## Dropped classes per view",
        "",
    ]
    for a in audits.values():
        lines.append(f"### Held-out view {a.view}")
        lines.append("")
        lines.append(f"Too few support ({len(a.dropped_too_few_support)} classes):")
        lines.append("")
        lines.append(", ".join(f"`{c}`" for c in a.dropped_too_few_support) or "none")
        lines.append("")
        lines.append(f"No test image ({len(a.dropped_no_test)} classes):")
        lines.append("")
        lines.append(", ".join(f"`{c}`" for c in a.dropped_no_test) or "none")
        lines.append("")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines))
    return path


class CrossViewSplitResult(BaseModel):
    seed: int
    report_path: Path
    audits: dict[int, ViewEligibility]
    outputs: dict[int, SplitManifestOutputs]
    class_counts: dict[int, int]
    partition_counts: dict[int, dict[str, int]]


def build_cross_view_splits(
    split: pd.DataFrame,
    seed: int,
    views: list[int],
    thresholds: CrossViewThresholds,
    report_path: Path,
    out_dir: Path,
) -> CrossViewSplitResult:
    """Audit every view, write the report, then write ``view_<v>.parquet`` per view."""
    audits = {v: audit_cross_view(split, v, thresholds) for v in views}
    write_cross_view_report(audits, seed, report_path)
    outputs, class_counts, partition_counts = {}, {}, {}
    for v in views:
        variant = cross_view_variant(split, v, thresholds)
        outputs[v] = write_split_manifest(split_table(variant), out_dir / f"view_{v}.parquet")
        class_counts[v] = audits[v].classes_after
        partition_counts[v] = audits[v].images_after
    return CrossViewSplitResult(
        seed=seed,
        report_path=report_path,
        audits=audits,
        outputs=outputs,
        class_counts=class_counts,
        partition_counts=partition_counts,
    )
